// Перемешать массив (Fisher–Yates)
function shuffleArray(arr) {
  const a = [...arr]
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[a[i], a[j]] = [a[j], a[i]]
  }
  return a
}

export function getQuestionsForPositions(positions) {
  let questions
  if (!positions || positions.length === 0) {
    questions = IQ_QUESTIONS.default
  } else {
    const main = positions[0]
    const second = positions[1]
    if (!second) {
      questions = IQ_QUESTIONS[main] || IQ_QUESTIONS.default
    } else {
      const mainQs = IQ_QUESTIONS[main] || IQ_QUESTIONS.default
      const secondQs = IQ_QUESTIONS[second] || IQ_QUESTIONS.default
      const mixed = []
      for (let i = 0; i < 4; i++) {
        if (mainQs[i]) mixed.push(mainQs[i])
        if (secondQs[i]) mixed.push(secondQs[i])
      }
      questions = mixed
    }
  }
  // Перемешиваем вопросы и варианты ответов
  return shuffleArray(questions).map((q) => ({
    ...q,
    options: shuffleArray(q.options),
  }))
}

