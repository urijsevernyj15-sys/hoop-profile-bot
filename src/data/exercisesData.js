// ПОЛУЧИТЬ УПРАЖНЕНИЕ ПО ID
// ============================================================
export function getExerciseById(id) {
  return EXERCISES.find((e) => e.id === id) || null
}

// ============================================================
// ПОЛУЧИТЬ УПРАЖНЕНИЯ ПО ФИЛЬТРУ
// ============================================================
export function getExercisesByFilter({
  category,
  type,
  level,
  position,
  gear,
  count = 1,
}) {
  let result = EXERCISES.filter((ex) => {
    if (category && ex.category !== category) return false
    if (type && ex.type !== type) return false
    if (level && ex.levels && !ex.levels.includes(level)) return false
    if (position && ex.positions && !ex.positions.includes(position)) return false
    if (gear && gear.length > 0) {
      const hasAllGear = ex.gear.every((g) => gear.includes(g))
      if (!hasAllGear) return false
    }
    return true
  })

  result = [...result].sort(() => Math.random() - 0.5)
  return result.slice(0, count)
}

// ============================================================
// ПОЛУЧИТЬ ТРЕНИРОВКУ ПО ПРОГРАММЕ И УРОВНЮ
// ============================================================
export function getTrainingSession({
  program,
  level,
  position,
  gear,
  dayIndex = 0,
}) {
  const plan = {
    beginner:     { warmup: 1, main: 1, cooldown: 1 },
    intermediate: { warmup: 2, main: 2, cooldown: 1 },
    advanced:     { warmup: 2, main: 4, cooldown: 1 },
  }[level] || { warmup: 1, main: 1, cooldown: 1 }

  const mainCategories = (program && program.mainCategories) || ['shooting']
  const mainCategory = mainCategories[dayIndex % mainCategories.length]

  const warmup = getExercisesByFilter({
    type: 'warmup',
    level,
    position,
    gear,
    count: plan.warmup,
  })

  const main = getExercisesByFilter({
    category: mainCategory,
    type: 'main',
    level,
    position,
    gear,
    count: plan.main,
  })

  const cooldown = getExercisesByFilter({
    type: 'cooldown',
    level,
    position,
    gear,
    count: plan.cooldown,
  })

  const exercises = [
    ...warmup.map((ex) => ({ ...ex, section: 'warmup', sectionLabel: '🔥 Разминка' })),
    ...main.map((ex) => ({ ...ex, section: 'main', sectionLabel: '🎯 Основная часть' })),
    ...cooldown.map((ex) => ({ ...ex, section: 'cooldown', sectionLabel: '🧘 Заминка' })),
  ]

  const totalDuration = exercises.reduce((sum, ex) => sum + (ex.duration || 5), 0)

  return {
    exercises,
    totalDuration,
    totalExercises: exercises.length,
    mainCategory,
  }
}