// ============================================================
// ПОЛУЧИТЬ УПРАЖНЕНИЯ ПО ФИЛЬТРУ
// ============================================================
export function getExercisesByFilter({
  category,
  type,
  level,
  position,
  gear,
  count = 1,
}) {
  let result = EXERCISES.filter((ex) => {
    if (category && ex.category !== category) return false
    if (type && ex.type !== type) return false
    if (level && ex.levels && !ex.levels.includes(level)) return false
    if (position && ex.positions && !ex.positions.includes(position)) return false
    if (gear && gear.length > 0) {
      const hasAllGear = ex.gear.every((g) => gear.includes(g))
      if (!hasAllGear) return false
    }
    return true
  })

  result = [...result].sort(() => Math.random() - 0.5)
  return result.slice(0, count)
}

